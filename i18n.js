function lang() {
  var name = ""
  try { name = String(Qt.locale().name || "") } catch (e) { name = "" }
  var l = name.substring(0, 2).toLowerCase()
  return table[l] ? l : "en"
}

function t(key) {
  var l = lang()
  var s = (table[l] && table[l][key]) || (table.en && table.en[key]) || String(key)
  for (var i = 1; i < arguments.length; i++) s = s.replace("%" + i, String(arguments[i]))
  return s
}
